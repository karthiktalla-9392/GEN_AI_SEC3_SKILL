import unittest

from llm_client import DemoProvider, LLMClient


class FakeProvider:
    def generate(self, prompt: str) -> str:
        return "AI stands for Artificial Intelligence."


class TestLLMClient(unittest.TestCase):
    def test_generate_uses_provider(self) -> None:
        client = LLMClient(FakeProvider())
        result = client.generate("Explain AI")
        self.assertEqual(result, "AI stands for Artificial Intelligence.")

    def test_demo_answers_ai_question(self) -> None:
        result = DemoProvider().generate(
            "What is artificial intelligence? Explain it simply."
        )
        self.assertIn("Artificial intelligence (AI)", result)
        self.assertIn("not generated by an AI model", result)


if __name__ == "__main__":
    unittest.main()
