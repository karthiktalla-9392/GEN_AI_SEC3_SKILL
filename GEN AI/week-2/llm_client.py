from abc import ABC, abstractmethod

class LLMProvider(ABC):
    @abstractmethod
    def generate(self, prompt: str) -> str:
        raise NotImplementedError


class GeminiProvider(LLMProvider):
    def __init__(self, api_key: str, model: str = "gemini-3.8-flash") -> None:
        from google import genai

        self.client = genai.Client(api_key=api_key)
        self.model = model

    def generate(self, prompt: str) -> str:
        response = self.client.models.generate_content(
            model=self.model,
            contents=prompt,
        )
        if not response.text:
            raise RuntimeError("Gemini returned an empty response.")
        return response.text


class OllamaProvider(LLMProvider):
    def __init__(
        self,
        model: str = "llama3.2",
        url: str = "http://localhost:11434/api/generate",
    ) -> None:
        self.model = model
        self.url = url

    def generate(self, prompt: str) -> str:
        import requests

        response = requests.post(
            self.url,
            json={"model": self.model, "prompt": prompt, "stream": False},
            timeout=120,
        )
        response.raise_for_status()
        result = response.json().get("response")
        if not isinstance(result, str) or not result.strip():
            raise RuntimeError("Ollama returned an empty or invalid response.")
        return result


class DemoProvider(LLMProvider):
    def generate(self, prompt: str) -> str:
        normalized_prompt = prompt.casefold()
        if "artificial intelligence" in normalized_prompt or "what is ai" in normalized_prompt:
            return (
                "Offline demo sample (not generated by an AI model): "
                "Artificial intelligence (AI) is technology that helps "
                "computers do tasks that usually need human intelligence, "
                "such as understanding language or recognizing images."
            )
        return (
            "Offline demo mode does not generate custom answers. "
            "Choose Gemini or Ollama for a live model response."
        )


class LLMClient:
    def __init__(self, provider: LLMProvider) -> None:
        self.provider = provider

    def generate(self, prompt: str) -> str:
        return self.provider.generate(prompt)
